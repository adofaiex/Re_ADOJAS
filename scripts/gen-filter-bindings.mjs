#!/usr/bin/env node
/**
 * Extract per-filter material uniform bindings from ADOUAC FilterPrograms.Generated.cs.
 * Output: src/lib/Filters/generated/bindings.generated.ts
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const srcPath = path.join(root, '.adofai/ADOUAC/Assets/Adouac/View/Effects/Filters/FilterPrograms.Generated.cs');
const outPath = path.join(root, 'src/lib/Filters/generated/bindings.generated.ts');
if (!fs.existsSync(srcPath)) throw new Error('FilterPrograms.Generated.cs missing');
const text = fs.readFileSync(srcPath, 'utf8');

function findBody(startIndex) {
    let brace = text.indexOf('{', startIndex);
    if (brace < 0) return null;
    let depth = 0;
    for (let i = brace; i < text.length; i++) {
        if (text[i] === '{') depth++;
        else if (text[i] === '}') {
            depth--;
            if (depth === 0) return text.slice(brace + 1, i);
        }
    }
    return null;
}

const result = {};
const funcRe = /private\s+static\s+void\s+Apply_([A-Za-z0-9_]+)\s*\(/g;
for (const m of text.matchAll(funcRe)) {
    const component = m[1];
    const body = findBody(m.index + m[0].length);
    if (!body) continue;
    const locals = new Map();
    const fieldRe = /\b(?:float|int)\s+([A-Za-z_]\w*)\s*=\s*v\[(\d+)\]\s*;/g;
    for (const fm of body.matchAll(fieldRe)) {
        const index = Number(fm[2]);
        if (index % 4 === 0) locals.set(fm[1], { kind: 'field', index: index / 4 });
    }
    for (const cm of body.matchAll(/\bColor\s+([A-Za-z_]\w*)\s*=\s*new\s+Color\(([^)]*)\)/g)) {
        const nums = [...cm[2].matchAll(/v\[(\d+)\]/g)].map(x => Number(x[1]));
        if (nums.length && nums[0] % 4 === 0) locals.set(cm[1], { kind: 'field', index: nums[0] / 4 });
    }
    for (const vm of body.matchAll(/\bVector2\s+([A-Za-z_]\w*)\s*=\s*new\s+Vector2\(([^)]*)\)/g)) {
        const nums = [...vm[2].matchAll(/v\[(\d+)\]/g)].map(x => Number(x[1]));
        if (nums.length && nums[0] % 4 === 0) locals.set(vm[1], { kind: 'field', index: nums[0] / 4 });
    }
    for (const tm of body.matchAll(/\b(?:float|int)\s+([A-Za-z_]\w*)\s*=\s*f\.TimeX\s*;/g)) {
        locals.set(tm[1], { kind: 'time' });
    }
    for (const tm of body.matchAll(/\b(?:float|int)\s+([A-Za-z_]\w*)\s*=\s*(-?[\d.]+)f?\s*;/g)) {
        locals.set(tm[1], { kind: 'constant', value: Number(tm[2]) });
    }
    for (const tm of body.matchAll(/\bTexture(?:2D)?\s+([A-Za-z_]\w*)\s*=\s*f\.Texture\("([^"]+)"\)/g)) {
        locals.set(tm[1], { kind: 'texture', name: tm[2] });
    }

    const uniforms = {};
    const setRe = /material\.Set(Float|Color|Vector|Texture)\("([^"]+)",\s*([^;]+?)\);/g;
    for (const sm of body.matchAll(setRe)) {
        const [, setter, uniform, exprRaw] = sm;
        const expr = exprRaw.trim();
        let binding = locals.get(expr);
        if (!binding) {
            if (/^f\.Width\s*,\s*f\.Height\s*,\s*0(?:f)?\s*,\s*0(?:f)?$/.test(expr)) {
                binding = { kind: 'screenResolution' };
            } else if (/^f\.Width\s*,\s*f\.Height$/.test(expr)) {
                binding = { kind: 'screenSize' };
            } else if (/^-?[\d.]+f?$/.test(expr)) {
                binding = { kind: 'constant', value: Number(expr.replace(/f$/, '')) };
            } else if (expr === 'Texture2') {
                binding = { kind: 'texture', name: null };
            }
        }
        const uniformKind = setter === 'Float' ? 'float' : setter === 'Texture' ? 'texture' : 'vec4';
        if (binding) uniforms[uniform] = { ...binding, uniformKind };
    }
    result[component] = uniforms;
}

const lines = [
    '// AUTO-GENERATED by scripts/gen-filter-bindings.mjs. Do not edit by hand.',
    '',
    'export type FilterBinding =',
    "    | { kind: 'field'; index: number; uniformKind: 'float' | 'vec4' | 'texture' }",
    "    | { kind: 'time' | 'screenResolution' | 'screenSize'; uniformKind: 'float' | 'vec4' }",
    "    | { kind: 'constant'; value: number; uniformKind: 'float' | 'vec4' }",
    "    | { kind: 'texture'; name: string | null; uniformKind: 'texture' }",
    '',
    'export const GENERATED_FILTER_BINDINGS: Record<string, Record<string, FilterBinding>> = {',
];
for (const component of Object.keys(result).sort()) {
    const entries = Object.entries(result[component]);
    if (!entries.length) {
        lines.push(`    ${JSON.stringify(component)}: {},`);
        continue;
    }
    lines.push(`    ${JSON.stringify(component)}: {`);
    for (const [uniform, binding] of entries) {
        lines.push(`        ${JSON.stringify(uniform)}: ${JSON.stringify(binding)},`);
    }
    lines.push('    },');
}
lines.push('};', '');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`wrote ${path.relative(root, outPath)}: ${Object.keys(result).length} components, ${Object.values(result).reduce((n, u) => n + Object.keys(u).length, 0)} bindings`);
