#!/usr/bin/env node
/**
 * Generate the filter catalog from ADOUAC's generated C# tables.
 *
 * Source of truth:
 *   .adofai/ADOUAC/Assets/Adouac/Core/Effects/FilterCatalog.Generated.cs
 *   .adofai/ADOUAC/Assets/Adouac/View/Effects/Filters/FilterPrograms.Generated.cs
 *   .adofai/ADOUAC/Assets/Adouac/Core/Effects/FilterTimeline.cs
 *
 * This script only extracts metadata (filter names, fields, defaults, shader key,
 * SetFilter component aliases). It does not port shader code.
 *
 * Usage:
 *   node scripts/gen-filter-catalog.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const catalogPath = path.join(root, '.adofai/ADOUAC/Assets/Adouac/Core/Effects/FilterCatalog.Generated.cs');
const programsPath = path.join(root, '.adofai/ADOUAC/Assets/Adouac/View/Effects/Filters/FilterPrograms.Generated.cs');
const timelinePath = path.join(root, '.adofai/ADOUAC/Assets/Adouac/Core/Effects/FilterTimeline.cs');
const outPath = path.join(root, 'src/lib/Filters/catalog.generated.ts');

for (const file of [catalogPath, programsPath, timelinePath]) {
    if (!fs.existsSync(file)) throw new Error(`missing source file: ${file}`);
}

const catalogText = fs.readFileSync(catalogPath, 'utf8');
const programsText = fs.readFileSync(programsPath, 'utf8');
const timelineText = fs.readFileSync(timelinePath, 'utf8');

const filters = [];
const filterInfoRe = /new FilterInfo\("([^"]+)",\s*(new FilterField\[0\]|new\[\]\s*\{[\s\S]*?\})\s*\)/g;
for (const m of catalogText.matchAll(filterInfoRe)) {
    const name = m[1];
    const fields = [];
    const fieldRe = /new FilterField\("([^"]+)", FilterFieldKind\.(Float|Int|Color|Vector2), (-?[\d.]+)f, (-?[\d.]+)f, (-?[\d.]+)f, (-?[\d.]+)f\)/g;
    for (const f of m[2].matchAll(fieldRe)) {
        fields.push({
            name: f[1],
            kind: f[2],
            values: [Number(f[3]), Number(f[4]), Number(f[5]), Number(f[6])],
        });
    }
    filters.push({ name, shader: null, fields });
}

const shaderBlock = programsText.match(/Shaders\s*=\s*\{([\s\S]*?)\};/);
const shaderNames = [];
if (shaderBlock) {
    for (const line of shaderBlock[1].split(/\r?\n/)) {
        const quoted = line.match(/^\s*"([^"]+)",/);
        if (quoted) { shaderNames.push(quoted[1]); continue; }
        if (/^\s*null,/.test(line)) shaderNames.push(null);
    }
}
for (let i = 0; i < filters.length; i++) filters[i].shader = shaderNames[i] ?? null;

const setFilterComponents = {};
const setFilterOrder = [];
const componentRe = /\("([^"]+)",\s*FilterSlotKind\.Filter,\s*new\[\]\s*\{([^}]*)\}\)/g;
for (const m of timelineText.matchAll(componentRe)) {
    const component = m[1];
    for (const fm of m[2].matchAll(/"([^"]+)"/g)) {
        setFilterComponents[fm[1]] = component;
        setFilterOrder.push(fm[1]);
    }
}

const sceneValues = {};
const sceneBlock = timelineText.match(/SceneValues\s*=\s*\{([\s\S]*?)\};/);
if (sceneBlock) {
    const re = /\("([^"]+)",\s*"([^"]+)",\s*(-?[\d.]+)f,\s*(-?[\d.]+)f,\s*(-?[\d.]+)f,\s*(-?[\d.]+)f\)/g;
    for (const m of sceneBlock[1].matchAll(re)) {
        const [component, field] = [m[1], m[2]];
        (sceneValues[component] ??= {})[field] = [Number(m[3]), Number(m[4]), Number(m[5]), Number(m[6])];
    }
}

const stable = [...filters].sort((a, b) => a.name.localeCompare(b.name));
const lines = [];
lines.push('// AUTO-GENERATED by scripts/gen-filter-catalog.mjs. Do not edit by hand.');
lines.push('// Metadata only: filter names, public fields/defaults, Unity shader keys, aliases.');
lines.push('');
lines.push("export type GeneratedFilterFieldKind = 'Float' | 'Int' | 'Color' | 'Vector2';");
lines.push('');
lines.push('export interface GeneratedFilterField {');
lines.push('    name: string;');
lines.push('    kind: GeneratedFilterFieldKind;');
lines.push('    /** Unity defaults: Color=rgba, Vector2=xy, scalar=x. */');
lines.push('    values: [number, number, number, number];');
lines.push('}');
lines.push('');
lines.push('export interface GeneratedFilterDefinition {');
lines.push('    name: string;');
lines.push('    /** Unity shader key, null when the original game had no shader. */');
lines.push('    shader: string | null;');
lines.push('    fields: GeneratedFilterField[];');
lines.push('}');
lines.push('');
lines.push('export const GENERATED_FILTERS: GeneratedFilterDefinition[] = [');
for (const f of stable) {
    const fields = f.fields.map(field => `{ name: ${JSON.stringify(field.name)}, kind: ${JSON.stringify(field.kind)}, values: [${field.values.join(', ')}] }`).join(', ');
    lines.push(`    { name: ${JSON.stringify(f.name)}, shader: ${f.shader ? JSON.stringify(f.shader) : 'null'}, fields: [${fields}] },`);
}
lines.push('];');
lines.push('');
lines.push('export const GENERATED_FILTER_BY_NAME: Record<string, GeneratedFilterDefinition> = Object.fromEntries(');
lines.push('    GENERATED_FILTERS.map(f => [f.name, f]),');
lines.push(');');
lines.push('');
lines.push('/** SetFilter enum name -> original CameraFilterPack component name. */');
lines.push('export const SET_FILTER_COMPONENTS: Record<string, string> = {');
for (const name of Object.keys(setFilterComponents).sort()) {
    lines.push(`    ${JSON.stringify(name)}: ${JSON.stringify(setFilterComponents[name])},`);
}
lines.push('};');
lines.push('');
lines.push('/** Original foreground component order for SetFilter filters. */');
lines.push('export const SET_FILTER_ORDER: string[] = [');
for (const name of setFilterOrder) lines.push(`    ${JSON.stringify(name)},`);
lines.push('];');
lines.push('');
lines.push('/** Original scene serialized values that differ from the component defaults. */');
lines.push('export const SCENE_FILTER_VALUES: Record<string, Record<string, [number, number, number, number]>> = {');
for (const component of Object.keys(sceneValues).sort()) {
    const fields = Object.keys(sceneValues[component]).sort().map(field => `${JSON.stringify(field)}: [${sceneValues[component][field].join(', ')}]`).join(', ');
    lines.push(`    ${JSON.stringify(component)}: { ${fields} },`);
}
lines.push('};');
lines.push('');

fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`wrote ${path.relative(root, outPath)}: ${stable.length} filters, ${shaderNames.length} shader keys, ${Object.keys(setFilterComponents).length} SetFilter aliases`);
